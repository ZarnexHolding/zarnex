"""
Builds the company logos the WebGL constellation draws in particles, and the
typed manifest the scene and the tests read. Requires Pillow and PyMuPDF.

    python scripts/build-constellation.py

When the homepage mark disperses, each company with an entry here forms its
logo instead of a point of light. The particles are sampled from these files'
alpha at runtime, and coloured from their pixels when the mark is full colour.

Sources are the site's own logo files — the dark-ground variant where one
exists, since the scene is on the dark ground. Each output is:
  - trimmed to its opaque pixels, so the manifest's aspect IS the visual
    aspect (the layout guard in test:camera sizes nodes from it);
  - capped at 320px on its long side AND ~40k pixels — sampling ~3,000
    particles needs no more, and these download on every homepage visit.
    Uncapped, ENER-G alone was 102kB;
  - for single-colour marks, recoloured to white so the shader can tint them
    with the company accent. Colour is detected from the pixels, not declared.

Full logos, not icons: drawn at ~150px in ~2,000 particles, BuildX's X-only
icon and X Live's X are indistinguishable. The wordmarks read.
"""
import json
import os

import fitz
import numpy as np
from PIL import Image, ImageFilter

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT_DIR = os.path.join(ROOT, "public", "logos", "constellation")
MANIFEST = os.path.join(ROOT, "src", "components", "scene", "constellationLogos.ts")
MAX_SIDE = 320
MAX_PIXELS = 40_000

# slug -> source file under public/. Order is irrelevant; output is sorted.
RECIPES = {
    "realintelligence": "logos/realintelligence-on-dark.png",
    "lumen-arabia": "logos/lumen-on-dark.png",
    "x-live": "logos/x-live.png",
    "buildx": "logos/buildx.png",
    "glitch-morph": "logos/glitch-morph-on-dark.png",
    "energ": "logos/energ.png",
    "ifmc": "logos/ifmc.svg",
    "port-l": "logos/port-l-on-dark.png",
}

# Pixels to erode from a heavy mark's strokes, in output pixels. IFMC is ~80%
# ink with gaps ~2px wide on screen: drawn in particles it is a solid block.
# Insetting the ink opens the gaps back up. A particle rendition only — the
# site's own IFMC logo is untouched. Thin-stroked marks must not be listed.
INSET = {
    "ifmc": 2,
}


def load(path):
    if path.endswith(".svg"):
        pix = fitz.open(path)[0].get_pixmap(dpi=600, alpha=True)
        return Image.frombytes("RGBA", (pix.width, pix.height), pix.samples)
    return Image.open(path).convert("RGBA")


def process(path, inset=0):
    im = load(path)
    a = np.asarray(im)
    ys, xs = np.nonzero(a[..., 3] > 12)
    im = im.crop((xs.min(), ys.min(), xs.max() + 1, ys.max() + 1))
    s = min(1.0, MAX_SIDE / max(im.size), (MAX_PIXELS / (im.width * im.height)) ** 0.5)
    if s < 1.0:
        im = im.resize((max(1, round(im.width * s)), max(1, round(im.height * s))), Image.LANCZOS)

    if inset:
        r, g, b, alpha = im.split()
        im = Image.merge("RGBA", (r, g, b, alpha.filter(ImageFilter.MinFilter(2 * inset + 1))))

    a = np.asarray(im).copy()
    opaque = a[..., 3] > 128
    rgb = a[..., :3].astype(int)[opaque]
    # A single-colour mark has no chroma and one tone; anything else is colour.
    spread = int((rgb.max(-1) - rgb.min(-1)).max()) if rgb.size else 0
    tone = int(rgb.mean(-1).std()) if rgb.size else 0
    colour = spread > 40 or tone > 40
    if not colour:
        # White + alpha, stored as greyscale-alpha: the shader tints it.
        a[..., :3] = 255
        return Image.fromarray(a, "RGBA").convert("LA"), colour
    # Palette-reduced: particles sample a few thousand pixels, so 192 colours
    # are indistinguishable from the original and a fraction of the bytes.
    return Image.fromarray(a, "RGBA").quantize(192, method=Image.Quantize.FASTOCTREE), colour


os.makedirs(OUT_DIR, exist_ok=True)
entries = {}
for slug in sorted(RECIPES):
    im, colour = process(os.path.join(ROOT, "public", RECIPES[slug]), INSET.get(slug, 0))
    out = os.path.join(OUT_DIR, f"{slug}.png")
    im.save(out, optimize=True)
    entries[slug] = {"src": f"/logos/constellation/{slug}.png", "w": im.width,
                     "h": im.height, "colour": colour}
    print(f"  {slug:18s} {im.width:>3}x{im.height:<3} {'colour' if colour else 'accent'}  "
          f"{os.path.getsize(out) // 1024}kB")

body = "\n".join(f"  {json.dumps(k)}: {json.dumps(v, separators=(', ', ': '))}," for k, v in entries.items())
ts = f'''/**
 * Company logos drawn by the constellation. GENERATED by
 * scripts/build-constellation.py — edit its RECIPES, not this file.
 *
 * w/h are the trimmed file's own pixels, so the aspect is the visual aspect.
 * `colour` is detected from the pixels: true samples each particle's colour
 * from the logo; false means a white silhouette the shader tints with the
 * company accent. A company with no entry stays a point of light.
 */

export type ConstellationLogo = {{
  src: string;
  w: number;
  h: number;
  colour: boolean;
}};

export const CONSTELLATION_LOGOS: Record<string, ConstellationLogo> = {{
{body}
}};
'''
with open(MANIFEST, "w", encoding="utf-8", newline="\n") as f:
    f.write(ts)
print(f"build:constellation — {len(entries)} logos -> {os.path.relpath(MANIFEST, ROOT)}")
